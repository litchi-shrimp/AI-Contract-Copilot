"""最终兜底：通用合同骨架（所有大纲生成策略都失败时使用，保证流程不中断）"""

GENERIC_SECTIONS = [
    ("定义与解释", ["本合同所用术语的定义与解释规则"]),
    ("合同标的与范围", ["合同标的、服务/交付内容的范围与标准"]),
    ("双方权利与义务", ["甲方的权利与义务", "乙方的权利与义务"]),
    ("价款与支付", ["价款/费用构成与金额：{合同总价款}", "支付方式、支付节点与发票"]),
    ("履行期限与验收", ["履行期限：自{开始日期}至{结束日期}", "交付与验收标准、程序"]),
    ("保密", ["保密信息范围、保密义务及期限"]),
    ("知识产权", ["知识产权归属与使用许可"]),
    ("违约责任", ["违约情形", "违约金计算方式与赔偿上限", "守约方的救济权利"]),
    ("合同变更与解除", ["变更程序", "解除条件与解除后的处理"]),
    ("不可抗力", ["不可抗力的范围、通知义务与责任免除"]),
    ("争议解决", ["适用法律", "争议解决方式与管辖：{争议解决机构}"]),
    ("其他约定", ["通知与送达", "合同生效、份数与附件"]),
]


def generic_skeleton(user_need: dict) -> dict:
    c = (user_need or {}).get("collected", {}) or {}
    ctype = str(c.get("contract_type") or "合同").split(".")[-1]
    if ctype in ("ELSE", "None", "未指定"):
        ctype = "合同"
    extras = (user_need or {}).get("extra_need", []) or []
    sections = []
    for i, (title, clauses) in enumerate(GENERIC_SECTIONS, 1):
        sections.append({"章节编号": f"第{i}条", "章节标题": title,
                         "条款列表": [{"条款编号": f"{i}.{j}", "条款大致说明": t, "子条款列表": []}
                                  for j, t in enumerate(clauses, 1)]})
    if extras:
        n = len(sections) + 1
        sections.insert(-1, {"章节编号": f"第{n}条", "章节标题": "特别约定",
                             "条款列表": [{"条款编号": f"{n}.{j}", "条款大致说明": str(t), "子条款列表": []}
                                      for j, t in enumerate(extras, 1)]})
    return {
        "标准化模板文本": {
            "合同首部": f"{ctype}\n合同编号：{{合同编号}}\n甲方：{{甲方名称}}\n乙方：{{乙方名称}}\n"
                       f"双方本着平等自愿、诚实信用的原则，经协商一致，订立本合同。",
            "正文章节": sections,
            "合同尾部": "甲方（盖章）：{甲方名称}    乙方（盖章）：{乙方名称}\n签订日期：{签订日期}",
        },
        "思考": "（兜底）大纲生成服务不可用，已使用通用合同骨架，请在大纲确认阶段补充调整。",
    }
